/** Position of a longitude / latitude on the grid, in columns and rows. */
export function gridOf([lon, lat]: [number, number]): { col: number; row: number } {
  return { col: (lon + 180) / MAP_STEP - 0.5, row: (MAP_TOP - lat) / MAP_STEP };
}
